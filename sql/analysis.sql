USE DATABASE FINANCIAL_WAREHOUSE;

-- 1. Source-to-target record reconciliation
SELECT
    (SELECT COUNT(*) FROM RAW.TRANSACTIONS) AS SOURCE_COUNT,
    (SELECT COUNT(*) FROM ANALYTICS.CLEAN_TRANSACTIONS) AS VALID_COUNT,
    (SELECT COUNT(*) FROM ANALYTICS.REJECTED_TRANSACTIONS) AS REJECTED_COUNT,
    CASE
        WHEN (SELECT COUNT(*) FROM RAW.TRANSACTIONS) =
             (SELECT COUNT(*) FROM ANALYTICS.CLEAN_TRANSACTIONS) +
             (SELECT COUNT(*) FROM ANALYTICS.REJECTED_TRANSACTIONS)
        THEN 'PASSED'
        ELSE 'FAILED'
    END AS RECONCILIATION_STATUS;

-- 2. Rejected records and reasons
SELECT *
FROM ANALYTICS.REJECTED_TRANSACTIONS
ORDER BY TRANSACTION_ID;

-- 3. Financial summary
SELECT
    COUNT(*) AS TOTAL_VALID_TRANSACTIONS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'DEPOSIT'
             THEN AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'WITHDRAWAL'
             THEN AMOUNT ELSE 0 END) AS TOTAL_WITHDRAWALS,
    SUM(SIGNED_AMOUNT) AS NET_CASH_FLOW
FROM ANALYTICS.CLEAN_TRANSACTIONS;

-- 4. Daily financial reporting
SELECT *
FROM ANALYTICS.DAILY_SUMMARY
ORDER BY TRANSACTION_DATE;

-- 5. Customer transaction summary
SELECT
    CUSTOMER_ID,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(SIGNED_AMOUNT) AS NET_CASH_FLOW
FROM ANALYTICS.CLEAN_TRANSACTIONS
GROUP BY CUSTOMER_ID
ORDER BY CUSTOMER_ID;

-- 6. Financial reconciliation
SELECT
    (SELECT SUM(SIGNED_AMOUNT)
     FROM ANALYTICS.CLEAN_TRANSACTIONS) AS DETAIL_NET_CASH_FLOW,
    (SELECT SUM(NET_CASH_FLOW)
     FROM ANALYTICS.DAILY_SUMMARY) AS SUMMARY_NET_CASH_FLOW,
    CASE
        WHEN (SELECT SUM(SIGNED_AMOUNT)
              FROM ANALYTICS.CLEAN_TRANSACTIONS) =
             (SELECT SUM(NET_CASH_FLOW)
              FROM ANALYTICS.DAILY_SUMMARY)
        THEN 'PASSED'
        ELSE 'FAILED'
    END AS FINANCIAL_RECONCILIATION;