USE DATABASE FINANCIAL_WAREHOUSE;

TRUNCATE TABLE ANALYTICS.CLEAN_TRANSACTIONS;
TRUNCATE TABLE ANALYTICS.REJECTED_TRANSACTIONS;
TRUNCATE TABLE ANALYTICS.DAILY_SUMMARY;

INSERT INTO ANALYTICS.REJECTED_TRANSACTIONS
SELECT
    TRANSACTION_ID,
    CUSTOMER_ID,
    TRANSACTION_DATE,
    TRANSACTION_TYPE,
    AMOUNT,
    ACCOUNT_TYPE,
    CASE
        WHEN TRANSACTION_ID IS NULL THEN 'Missing transaction ID'
        WHEN CUSTOMER_ID IS NULL THEN 'Missing customer ID'
        WHEN TRANSACTION_DATE IS NULL THEN 'Missing transaction date'
        WHEN AMOUNT IS NULL THEN 'Missing amount'
        WHEN AMOUNT <= 0 THEN 'Invalid transaction amount'
        WHEN TRANSACTION_TYPE NOT IN ('DEPOSIT', 'WITHDRAWAL')
             OR TRANSACTION_TYPE IS NULL
             THEN 'Invalid transaction type'
        ELSE 'Unknown validation error'
    END AS REJECTION_REASON
FROM RAW.TRANSACTIONS
WHERE
    TRANSACTION_ID IS NULL
    OR CUSTOMER_ID IS NULL
    OR TRANSACTION_DATE IS NULL
    OR AMOUNT IS NULL
    OR AMOUNT <= 0
    OR TRANSACTION_TYPE IS NULL
    OR TRANSACTION_TYPE NOT IN ('DEPOSIT', 'WITHDRAWAL');

INSERT INTO ANALYTICS.CLEAN_TRANSACTIONS
SELECT
    TRANSACTION_ID,
    CUSTOMER_ID,
    TRANSACTION_DATE,
    TRANSACTION_TYPE,
    AMOUNT,
    ACCOUNT_TYPE,
    CASE
        WHEN TRANSACTION_TYPE = 'DEPOSIT' THEN AMOUNT
        WHEN TRANSACTION_TYPE = 'WITHDRAWAL' THEN -AMOUNT
    END AS SIGNED_AMOUNT
FROM RAW.TRANSACTIONS
WHERE
    TRANSACTION_ID IS NOT NULL
    AND CUSTOMER_ID IS NOT NULL
    AND TRANSACTION_DATE IS NOT NULL
    AND AMOUNT IS NOT NULL
    AND AMOUNT > 0
    AND TRANSACTION_TYPE IN ('DEPOSIT', 'WITHDRAWAL');

INSERT INTO ANALYTICS.DAILY_SUMMARY
SELECT
    TRANSACTION_DATE,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(CASE WHEN TRANSACTION_TYPE = 'DEPOSIT'
             THEN AMOUNT ELSE 0 END) AS TOTAL_DEPOSITS,
    SUM(CASE WHEN TRANSACTION_TYPE = 'WITHDRAWAL'
             THEN AMOUNT ELSE 0 END) AS TOTAL_WITHDRAWALS,
    SUM(SIGNED_AMOUNT) AS NET_CASH_FLOW
FROM ANALYTICS.CLEAN_TRANSACTIONS
GROUP BY TRANSACTION_DATE;