CREATE DATABASE IF NOT EXISTS FINANCIAL_WAREHOUSE;

USE DATABASE FINANCIAL_WAREHOUSE;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;

CREATE OR REPLACE TABLE RAW.TRANSACTIONS (
    TRANSACTION_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    TRANSACTION_DATE DATE,
    TRANSACTION_TYPE VARCHAR(20),
    AMOUNT NUMBER(12,2),
    ACCOUNT_TYPE VARCHAR(30)
);

CREATE OR REPLACE TABLE ANALYTICS.CLEAN_TRANSACTIONS (
    TRANSACTION_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    TRANSACTION_DATE DATE,
    TRANSACTION_TYPE VARCHAR(20),
    AMOUNT NUMBER(12,2),
    ACCOUNT_TYPE VARCHAR(30),
    SIGNED_AMOUNT NUMBER(12,2)
);

CREATE OR REPLACE TABLE ANALYTICS.REJECTED_TRANSACTIONS (
    TRANSACTION_ID VARCHAR(20),
    CUSTOMER_ID VARCHAR(20),
    TRANSACTION_DATE DATE,
    TRANSACTION_TYPE VARCHAR(20),
    AMOUNT NUMBER(12,2),
    ACCOUNT_TYPE VARCHAR(30),
    REJECTION_REASON VARCHAR(200)
);

CREATE OR REPLACE TABLE ANALYTICS.DAILY_SUMMARY (
    TRANSACTION_DATE DATE,
    TRANSACTION_COUNT NUMBER,
    TOTAL_DEPOSITS NUMBER(12,2),
    TOTAL_WITHDRAWALS NUMBER(12,2),
    NET_CASH_FLOW NUMBER(12,2)
);